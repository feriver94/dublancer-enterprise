import { z } from "zod";

const id = z.string().min(8).max(128);
const shortText = z.string().trim().min(1).max(255);
const longText = z.string().trim().min(1).max(50_000);
const optionalText = z.string().trim().max(2_000).optional();
const money = z.coerce.number().int().nonnegative().max(Number.MAX_SAFE_INTEGER);
const percentage = z.coerce.number().int().min(0).max(100);
const isoDate = z.iso.datetime();
const metadata = z.record(z.string(), z.unknown()).optional();

export const crmActionSchema = z.discriminatedUnion("action", [
  z.object({
    action: z.literal("pipeline.create"),
    name: shortText,
    description: optionalText,
    isDefault: z.boolean().default(false),
    stages: z.array(z.object({
      name: shortText,
      probability: percentage,
      category: z.enum(["OPEN", "WON", "LOST"]).default("OPEN"),
    })).min(2).max(20),
  }),
  z.object({
    action: z.literal("lead.create"),
    firstName: shortText,
    lastName: shortText,
    email: z.email().optional(),
    phone: z.string().trim().max(50).optional(),
    companyName: optionalText,
    jobTitle: optionalText,
    source: optionalText,
    score: z.coerce.number().int().min(0).max(100).default(0),
    assignedToMembershipId: id.optional(),
    metadata,
  }),
  z.object({
    action: z.literal("lead.convert"),
    leadId: id,
    accountName: shortText,
    opportunityName: shortText,
    pipelineId: id,
    stageId: id,
    amountMinor: money,
    currency: z.string().trim().length(3).default("AED"),
  }),
  z.object({
    action: z.literal("account.create"),
    name: shortText,
    industry: optionalText,
    website: z.url().optional(),
    phone: z.string().trim().max(50).optional(),
    countryCode: z.string().trim().length(2).default("AE"),
    ownerMembershipId: id.optional(),
    parentAccountId: id.optional(),
    metadata,
  }),
  z.object({
    action: z.literal("contact.create"),
    accountId: id,
    firstName: shortText,
    lastName: shortText,
    email: z.email().optional(),
    phone: z.string().trim().max(50).optional(),
    jobTitle: optionalText,
    ownerMembershipId: id.optional(),
    isPrimary: z.boolean().default(false),
    metadata,
  }),
  z.object({
    action: z.literal("opportunity.create"),
    accountId: id,
    primaryContactId: id.optional(),
    pipelineId: id,
    stageId: id,
    ownerMembershipId: id.optional(),
    name: shortText,
    amountMinor: money,
    currency: z.string().trim().length(3).default("AED"),
    expectedCloseAt: isoDate.optional(),
    metadata,
  }),
  z.object({
    action: z.literal("opportunity.advance"),
    opportunityId: id,
    stageId: id,
    expectedVersion: z.coerce.number().int().positive(),
    lostReason: optionalText,
  }),
  z.object({
    action: z.literal("activity.create"),
    type: z.enum(["CALL", "EMAIL", "MEETING", "TASK", "NOTE", "SYSTEM"]),
    subject: shortText,
    details: optionalText,
    accountId: id.optional(),
    contactId: id.optional(),
    opportunityId: id.optional(),
    leadId: id.optional(),
    dueAt: isoDate.optional(),
    occurredAt: isoDate.optional(),
    metadata,
  }),
  z.object({
    action: z.literal("note.create"),
    body: longText,
    isPinned: z.boolean().default(false),
    accountId: id.optional(),
    contactId: id.optional(),
    opportunityId: id.optional(),
    leadId: id.optional(),
  }),
  z.object({
    action: z.literal("quote.create"),
    opportunityId: id,
    contactId: id.optional(),
    currency: z.string().trim().length(3).default("AED"),
    discountMinor: money.default(0),
    taxMinor: money.default(0),
    validUntil: isoDate.optional(),
    terms: optionalText,
    lines: z.array(z.object({
      description: shortText,
      quantity: z.coerce.number().int().positive().max(100_000),
      unitPriceMinor: money,
      metadata,
    })).min(1).max(200),
  }),
  z.object({
    action: z.literal("quote.transition"),
    quoteId: id,
    status: z.enum(["SENT", "ACCEPTED", "REJECTED", "EXPIRED"]),
    expectedVersion: z.coerce.number().int().positive(),
  }),
  z.object({
    action: z.literal("health.capture"),
    accountId: id,
    score: z.coerce.number().int().min(0).max(100),
    signals: z.record(z.string(), z.unknown()),
    source: shortText.default("RULE_ENGINE"),
  }),
  z.object({
    action: z.literal("metric.record"),
    accountId: id,
    key: z.string().trim().min(1).max(100),
    value: z.coerce.number().finite(),
    periodStart: isoDate,
    periodEnd: isoDate,
    metadata,
  }),
]);

