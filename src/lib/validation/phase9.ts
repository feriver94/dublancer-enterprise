export const integrationActionSchema = z.discriminatedUnion("action", [
  z.object({
    action: z.literal("connector.create"),
    name: shortText,
    key: z.string().trim().min(2).max(100).regex(/^[a-z0-9]+(?:[._-][a-z0-9]+)*$/),
    type: z.enum(["REST", "IMPORT", "EXPORT"]),
    baseUrl: z.url(),
    method: z.enum(["GET", "POST", "PUT", "PATCH"]).default("POST"),
    path: z.string().trim().startsWith("/").max(500).default("/"),
    authType: z.enum(["NONE", "API_KEY", "BEARER", "BASIC", "OAUTH2"]).default("NONE"),
    authConfig: z.record(z.string(), z.string()).optional(),
    defaultHeaders: z.record(z.string(), z.string()).optional(),
    requestTimeoutMs: z.coerce.number().int().min(500).max(60_000).default(15_000),
    maxAttempts: z.coerce.number().int().min(1).max(10).default(5),
    mapping: z.record(z.string(), z.unknown()).optional(),
    activate: z.boolean().default(true),
  }),
  z.object({
    action: z.literal("apiKey.create"),
    name: shortText,
    scopes: z.array(z.enum(["events.publish", "connectors.execute", "monitoring.read"])).min(1),
    expiresAt: isoDate.optional(),
  }),
  z.object({
    action: z.literal("apiKey.revoke"),
    apiKeyId: id,
  }),
  z.object({
    action: z.literal("oauth.upsert"),
    oauthId: id.optional(),
    connectorId: id.optional(),
    provider: shortText,
    name: shortText,
    clientId: shortText,
    clientSecret: z.string().min(8).max(5_000).optional(),
    authorizationUrl: z.url().optional(),
    tokenUrl: z.url().optional(),
    scopes: z.array(shortText).max(100).default([]),
    accessToken: z.string().min(8).max(20_000).optional(),
    refreshToken: z.string().min(8).max(20_000).optional(),
    tokenExpiresAt: isoDate.optional(),
    externalAccountReference: optionalText,
  }),
  z.object({
    action: z.literal("webhook.create"),
    name: shortText,
    url: z.url(),
    eventTypes: z.array(shortText).min(1).max(100),
    maxAttempts: z.coerce.number().int().min(1).max(10).default(5),
    timeoutMs: z.coerce.number().int().min(500).max(60_000).default(10_000),
  }),
  z.object({
    action: z.literal("subscription.create"),
    eventType: shortText,
    endpointId: id.optional(),
    connectorId: id.optional(),
    filters: z.record(z.string(), z.unknown()).optional(),
  }),
  z.object({
    action: z.literal("event.publish"),
    eventType: shortText,
    aggregateType: shortText,
    aggregateId: shortText,
    payload: z.record(z.string(), z.unknown()),
    correlationId: shortText.optional(),
  }),
  z.object({
    action: z.literal("connector.execute"),
    connectorId: id,
    idempotencyKey: z.string().trim().min(8).max(200),
    payload: z.record(z.string(), z.unknown()).optional(),
  }),
  z.object({
    action: z.literal("delivery.retry"),
    deliveryId: id,
  }),
]);

export const externalIntegrationEventSchema = z.object({
  eventType: shortText,
  aggregateType: shortText,
  aggregateId: shortText,
  payload: z.record(z.string(), z.unknown()),
  correlationId: shortText.optional(),
});

